export const dictionaries: Record<Locale, Dictionary> = { pt, en, es };

const I18nContext = createContext<{ locale: Locale; t: Dictionary }>({ locale: defaultLocale, t: pt });

export function I18nProvider({ locale, children }: { locale: Locale; children: ReactNode }) {
  return <I18nContext.Provider value={{ locale, t: dictionaries[locale] }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
